-- Devolución Parcial del Pedido
CREATE OR REPLACE FUNCTION public.admin_procesar_devolucion_parcial(
    p_item_id bigint, 
    p_cantidad_a_devolver integer, 
    p_usuario_nombre text, 
    p_pedido_id bigint
) RETURNS void AS $$
DECLARE
  v_producto_id bigint;
  v_cantidad_actual int;
  v_cantidad_ya_devuelta int;
  v_stock_descontado boolean;
BEGIN
  SELECT 
    pi.producto_id, 
    pi.cantidad, 
    pi.cantidad_devuelta,
    p.stock_descontado
  INTO 
    v_producto_id, 
    v_cantidad_actual, 
    v_cantidad_ya_devuelta,
    v_stock_descontado
  FROM pedido_items pi
  JOIN pedidos p ON p.id = pi.pedido_id
  WHERE pi.id = p_item_id;

  IF v_producto_id IS NULL THEN
    RAISE EXCEPTION 'El item no existe';
  END IF;

  IF (v_cantidad_ya_devuelta + p_cantidad_a_devolver) > v_cantidad_actual THEN
    RAISE EXCEPTION 'No puedes devolver más productos de los que se compraron';
  END IF;

  UPDATE pedido_items
  SET cantidad_devuelta = cantidad_devuelta + p_cantidad_a_devolver
  WHERE id = p_item_id;

  IF v_stock_descontado THEN
    -- Realizar un ingreso por devolución en Kardex para ajustar automáticamente el stock
    INSERT INTO public.inventario_movimientos (
        producto_id,
        almacen_id,
        tipo_movimiento,
        cantidad,
        costo_unitario,
        referencia,
        notas,
        created_at
    ) VALUES (
        v_producto_id,
        1,
        'DEVOLUCION',
        p_cantidad_a_devolver,
        public.get_costo_promedio(v_producto_id, null),
        'DEVOLUCION-PARCIAL-' || p_pedido_id::text,
        'Ingreso de stock por devolución parcial parcial',
        now()
    );
  END IF;

  INSERT INTO pedido_logs (pedido_id, usuario_nombre, accion, detalles)
  VALUES (
    p_pedido_id, 
    p_usuario_nombre, 
    'Devolución Parcial', 
    'Se devolvieron ' || p_cantidad_a_devolver || ' unidad(es) del producto ID ' || v_producto_id
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger: Logging en system_audit_logs
CREATE OR REPLACE FUNCTION public.log_changes_trigger()
RETURNS trigger AS $$
DECLARE
    sys_user UUID;
    record_identifier TEXT;
BEGIN
    sys_user := auth.uid();
    CASE TG_OP
        WHEN 'INSERT' THEN
            record_identifier := NEW.id::TEXT;
        WHEN 'UPDATE' THEN
            record_identifier := NEW.id::TEXT;
        WHEN 'DELETE' THEN
            record_identifier := OLD.id::TEXT;
    END CASE;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO system_audit_logs (table_name, record_id, action, new_data, changed_by)
        VALUES (TG_TABLE_NAME, record_identifier, 'INSERT', row_to_json(NEW)::jsonb, sys_user);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        IF NEW IS DISTINCT FROM OLD THEN
            INSERT INTO system_audit_logs (table_name, record_id, action, old_data, new_data, changed_by)
            VALUES (TG_TABLE_NAME, record_identifier, 'UPDATE', row_to_json(OLD)::jsonb, row_to_json(NEW)::jsonb, sys_user);
        END IF;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO system_audit_logs (table_name, record_id, action, old_data, changed_by)
        VALUES (TG_TABLE_NAME, record_identifier, 'DELETE', row_to_json(OLD)::jsonb, sys_user);
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Obtener Ventas para Gráfico de Ventas
CREATE OR REPLACE FUNCTION public.get_sales_chart_data(
    p_start_date date, 
    p_end_date date, 
    p_interval text
) RETURNS TABLE(day text, total numeric, cnt bigint) AS $$
BEGIN
  RETURN QUERY
  WITH series AS (
    SELECT generate_series(
      p_start_date::timestamp, 
      p_end_date::timestamp, 
      ('1 ' || p_interval)::interval
    )::date as day
  ),
  sales AS (
    SELECT 
      date_trunc(p_interval, created_at)::date as sales_day,
      SUM(total) as total,
      COUNT(*) as cnt
    FROM pedidos
    WHERE status = 'Entregado' 
      AND created_at >= p_start_date
      AND created_at < p_end_date + interval '1 day'
    GROUP BY 1
  )
  SELECT 
    to_char(s.day, 'YYYY-MM-DD'),
    COALESCE(sl.total, 0),
    COALESCE(sl.cnt, 0)
  FROM series s
  LEFT JOIN sales sl ON s.day = sl.sales_day
  ORDER BY s.day;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger: Sincronizar Stock desde el historial de movimientos de Kardex
CREATE OR REPLACE FUNCTION public.sync_stock_from_kardex()
RETURNS trigger AS $$
DECLARE
    calc_producto_id BIGINT;
    calc_variante_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        calc_producto_id := OLD.producto_id;
        calc_variante_id := OLD.variante_id;
    ELSE
        calc_producto_id := NEW.producto_id;
        calc_variante_id := NEW.variante_id;
    END IF;

    IF calc_variante_id IS NOT NULL THEN
        UPDATE public.producto_variantes 
        SET stock = (
            SELECT COALESCE(SUM(cantidad), 0)
            FROM public.inventario_movimientos
            WHERE variante_id = calc_variante_id
        )
        WHERE id = calc_variante_id;
    ELSE
        UPDATE public.productos
        SET stock = (
            SELECT COALESCE(SUM(cantidad), 0)
            FROM public.inventario_movimientos
            WHERE producto_id = calc_producto_id AND variante_id IS NULL
        )
        WHERE id = calc_producto_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Calcular costo promedio ponderado de stock
CREATE OR REPLACE FUNCTION public.get_costo_promedio(p_producto_id bigint, p_variante_id bigint)
RETURNS numeric AS $$
DECLARE
    v_total_cantidad INTEGER := 0;
    v_total_valor NUMERIC(15,2) := 0.00;
    v_mov RECORD;
BEGIN
    FOR v_mov IN 
        SELECT cantidad, costo_unitario, tipo_movimiento
        FROM public.inventario_movimientos
        WHERE producto_id = p_producto_id 
          AND (variante_id = p_variante_id OR (variante_id IS NULL AND p_variante_id IS NULL))
        ORDER BY created_at ASC, id ASC
    LOOP
        IF v_mov.cantidad > 0 THEN
            v_total_valor := v_total_valor + (v_mov.cantidad * v_mov.costo_unitario);
            v_total_cantidad := v_total_cantidad + v_mov.cantidad;
        ELSE
            IF v_total_cantidad > 0 THEN
                v_total_valor := v_total_valor + (v_mov.cantidad * (v_total_valor / v_total_cantidad));
            END IF;
            v_total_cantidad := v_total_cantidad + v_mov.cantidad;
        END IF;
    END LOOP;
    
    IF v_total_cantidad <= 0 THEN
        RETURN 0.00;
    END IF;
    
    RETURN ROUND(v_total_valor / v_total_cantidad, 2);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Descuento Atómico de Stock de Pedidos vía Movimiento Kardex
CREATE OR REPLACE FUNCTION public.admin_procesar_descuento_stock(
  p_pedido_id BIGINT,
  p_revertir BOOLEAN DEFAULT false
) RETURNS BOOLEAN AS $$
DECLARE
  v_item RECORD;
  v_mov_tipo TEXT;
  v_multiplicador INTEGER;
  v_costo_unitario NUMERIC(10,2);
BEGIN
  IF NOT p_revertir THEN
    v_mov_tipo := 'SALIDA_VENTA';
    v_multiplicador := -1;
  ELSE
    v_mov_tipo := 'DEVOLUCION'; 
    v_multiplicador := 1;
  END IF;

  FOR v_item IN 
    SELECT producto_id, producto_variante_id, cantidad 
    FROM pedido_items 
    WHERE pedido_id = p_pedido_id
  LOOP
    v_costo_unitario := public.get_costo_promedio(v_item.producto_id, v_item.producto_variante_id);

    INSERT INTO public.inventario_movimientos (
        producto_id, 
        variante_id, 
        almacen_id, 
        tipo_movimiento, 
        cantidad, 
        costo_unitario,
        referencia,
        notas
    ) VALUES (
        v_item.producto_id,
        v_item.producto_variante_id,
        1,
        v_mov_tipo,
        v_item.cantidad * v_multiplicador,
        v_costo_unitario,
        'PEDIDO-' || p_pedido_id::text,
        CASE WHEN p_revertir THEN 'Reversión de stock de pedido' ELSE 'Descuento de stock por venta' END
    );
  END LOOP;

  UPDATE pedidos 
  SET stock_descontado = NOT p_revertir 
  WHERE id = p_pedido_id;

  RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Obtener Productos Más Vendidos
CREATE OR REPLACE FUNCTION public.get_top_products(exclude_id bigint, limit_count integer)
RETURNS SETOF public.productos AS $$
BEGIN
  RETURN QUERY
  SELECT p.*
  FROM public.productos p
  LEFT JOIN public.pedido_items pi ON pi.producto_id = p.id
  LEFT JOIN public.pedidos pe ON pe.id = pi.pedido_id
  WHERE (exclude_id IS NULL OR p.id <> exclude_id)
    AND COALESCE(p.stock, 0) > 0
  GROUP BY p.id
  ORDER BY COALESCE(SUM(pi.cantidad), 0) DESC, p.created_at DESC
  LIMIT limit_count;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

