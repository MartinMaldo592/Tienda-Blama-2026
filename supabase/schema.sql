-- Comprobar si usuario es Staff (Admin, Superadmin, Worker)
CREATE OR REPLACE FUNCTION public.is_staff()
RETURNS boolean AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM public.usuarios u
    WHERE u.id = auth.uid()
      AND u.role IN ('admin', 'superadmin', 'worker')
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

