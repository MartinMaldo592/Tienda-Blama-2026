-- Kardex Valorizado View
CREATE OR REPLACE VIEW public.kardex_valorizado_view AS
 SELECT m.id,
    m.producto_id,
    p.nombre AS producto_nombre,
    m.variante_id,
    pv.etiqueta AS variante_nombre,
    m.almacen_id,
    a.nombre AS almacen_nombre,
    m.tipo_movimiento,
    m.referencia,
    m.notas,
    m.costo_unitario,
    m.cantidad,
        CASE
            WHEN (m.cantidad > 0) THEN m.cantidad
            ELSE 0
        END AS entradas,
        CASE
            WHEN (m.cantidad < 0) THEN abs(m.cantidad)
            ELSE 0
        END AS salidas,
    ((m.cantidad)::numeric * m.costo_unitario) AS valor_total,
    sum(m.cantidad) OVER (PARTITION BY m.producto_id, m.variante_id, m.almacen_id ORDER BY m.created_at, m.id) AS saldo_cantidad,
    m.created_at,
    m.created_by,
    u.nombre AS usuario_nombre,
    u.email AS usuario_email
   FROM ((((public.inventario_movimientos m
     LEFT JOIN public.productos p ON ((m.producto_id = p.id)))
     LEFT JOIN public.producto_variantes pv ON ((m.variante_id = pv.id)))
     LEFT JOIN public.almacenes a ON ((m.almacen_id = a.id)))
     LEFT JOIN public.usuarios u ON ((m.created_by = u.id)));

