-- Slugify utility
CREATE OR REPLACE FUNCTION public.slugify(value text)
RETURNS text AS $$
BEGIN
  RETURN trim(both '-' from regexp_replace(lower(value), '[^a-z0-9]+', '-', 'g'));
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- Trigger: Generar Slug de Producto
CREATE OR REPLACE FUNCTION public.handle_new_product_slug()
RETURNS trigger AS $$
DECLARE
  base_slug text;
  new_slug text;
BEGIN
  base_slug := public.slugify(NEW.nombre);
  new_slug := base_slug;
  IF EXISTS (SELECT 1 FROM public.productos WHERE slug = new_slug) THEN
     new_slug := base_slug || '-' || floor(random() * 10000)::text;
  END IF;
  NEW.slug := new_slug;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

